#!/usr/bin/env python3
"""Writes vectors.h: BLAKE2s test vectors from Python's hashlib, for test.c.

Covers what blake2-kat.h doesn't: unkeyed hashes, keys shorter than 32
bytes, salt, personalization and short digests. The message for length n
is bytes 0, 1, 2, ... n-1 (mod 256), as in the KAT.
Run: python3 vectors.py > vectors.h
"""
import hashlib

def msg(n):
    return bytes(i & 255 for i in range(n))

def c_bytes(b):
    return '"' + ''.join('\\x%02x' % x for x in b) + '"'

# (digest size, key length, salt, personal, message length)
cases = []
for n in (0, 1, 3, 63, 64, 65, 127, 128, 129, 255, 256, 1000, 4096):
    cases.append((32, 0, None, None, n))                  # plain hash
for k in (1, 16, 31, 32):
    for n in (0, 1, 64, 65, 300):
        cases.append((32, k, None, None, n))              # keys of any length
for d in (1, 16, 20, 31):
    cases.append((d, 0, None, None, 100))                 # short digests
    cases.append((d, 32, None, None, 100))
salts = [b'\x01\0\0\0\0\0\0\0', (0x0123456789ABCDEF).to_bytes(8, 'little'), b'saltsalt']
people = [b'LFblkMAC', b'LFkdf\0\0\0']
for s in salts:
    for n in (0, 64, 200):
        cases.append((32, 0, s, None, n))
        cases.append((32, 32, s, people[0], n))
for p in people:
    cases.append((32, 0, None, p, 50))
    cases.append((16, 16, salts[2], p, 50))

print('/* Generated by vectors.py from Python hashlib.blake2s; do not edit. */')
print('typedef struct { int hsize, keylen; const char *salt, *personal; int len; const char *hash; } b2s_vector;')
print('static const b2s_vector b2s_vectors[] = {')
for d, k, s, p, n in cases:
    key = bytes(range(k))                                  # key bytes 0, 1, 2, ...
    h = hashlib.blake2s(msg(n), digest_size=d, key=key,
                        salt=s or b'', person=p or b'').digest()
    print('  { %d, %d, %s, %s, %d, %s },' % (d, k, c_bytes(s) if s else 'NULL',
          c_bytes(p) if p else 'NULL', n, c_bytes(h)))
print('};')
