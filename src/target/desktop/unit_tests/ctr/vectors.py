#!/usr/bin/env python3
"""Writes vectors.h for test_ctr.c: AES-128 and SM4 in CTR mode as sealed
block files use it (counter nonce || n * 256 + i, big-endian), computed
with Python's cryptography package. Run: python3 vectors.py > vectors.h"""
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

def c_bytes(b):
    return '"' + ''.join('\\x%02x' % x for x in b) + '"'

cases = []
for cipher, alg in ((1, algorithms.AES), (2, algorithms.SM4)):
    for k, (n, length) in enumerate(((0, 16), (1, 100), (5, 4096), (0x123456, 4096),
                                     (0xFFFFFF, 33))):
        key = bytes((7 * k + 13 * i + cipher) & 255 for i in range(16))
        nonce = bytes((3 * k + 5 * i + 1) & 255 for i in range(8))
        plain = bytes((i * 31 + k) & 255 for i in range(length))
        ctr = nonce + (n * 256).to_bytes(8, 'big')
        out = Cipher(alg(key), modes.CTR(ctr)).encryptor().update(plain)
        cases.append((cipher, key, nonce, n, length, out[:48], out[-16:]))

print('/* Generated by vectors.py with the cryptography package; do not edit. */')
print('typedef struct { int cipher; const char *key, *nonce; unsigned long n; int len;')
print('                 const char *first, *last; } ctr_vector;')
print('static const ctr_vector ctr_vectors[] = {')
for cipher, key, nonce, n, length, first, last in cases:
    print('  { %d, %s,\n    %s, 0x%x, %d,\n    %s,\n    %s },' % (
        cipher, c_bytes(key), c_bytes(nonce), n, length, c_bytes(first), c_bytes(last)))
print('};')
